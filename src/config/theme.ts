// Get current theme based on THEME_NAME
export const CURRENT_THEME = THEMES[THEME_NAME];

/**
 * Applies the current theme's CSS variables to the document
 * This function should be called once on initial load
 */
export function applyTheme() {
  const root = document.documentElement;
  const theme = CURRENT_THEME;

  // Set theme variables
  setCSSVariables(root, theme);
}

/**
 * Helper function to set CSS variables on an element
 */
function setCSSVariables(root: HTMLElement, themeVars: Record<string, string>) {
  const varMap: Record<string, string> = {
    radius: '--radius',
    background: '--background',
    foreground: '--foreground',
    card: '--card',
    cardForeground: '--card-foreground',
    popover: '--popover',
    popoverForeground: '--popover-foreground',
    primary: '--primary',
    primaryForeground: '--primary-foreground',
    secondary: '--secondary',
    secondaryForeground: '--secondary-foreground',
    muted: '--muted',
    mutedForeground: '--muted-foreground',
    accent: '--accent',
    accentForeground: '--accent-foreground',
    destructive: '--destructive',
    destructiveForeground: '--destructive-foreground',
    border: '--border',
    input: '--input',
    ring: '--ring',
    chart1: '--chart-1',
    chart2: '--chart-2',
    chart3: '--chart-3',
    chart4: '--chart-4',
    chart5: '--chart-5',
    sidebar: '--sidebar',
    sidebarForeground: '--sidebar-foreground',
    sidebarPrimary: '--sidebar-primary',
    sidebarPrimaryForeground: '--sidebar-primary-foreground',
    sidebarAccent: '--sidebar-accent',
    sidebarAccentForeground: '--sidebar-accent-foreground',
    sidebarBorder: '--sidebar-border',
    sidebarRing: '--sidebar-ring',
  };

  Object.entries(varMap).forEach(([key, cssVar]) => {
    if (key in themeVars) {
      root.style.setProperty(cssVar, themeVars[key]);
    }
  });
}
